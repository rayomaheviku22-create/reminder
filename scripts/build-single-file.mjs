// Builds dist/worker-single-file.js: the Worker with the dashboard HTML embedded,
// so it can be pasted into the Cloudflare Dashboard code editor (no assets needed).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const worker = readFileSync('src/worker.js', 'utf8');
const html = readFileSync('public/index.html', 'utf8');

// Escape for a JS template literal: backslashes, backticks and ${
const literal = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const marker = 'const EMBEDDED_HTML = null;';
if (!worker.includes(marker)) throw new Error('Marker not found in src/worker.js');

const out =
  '// AUTO-GENERATED by scripts/build-single-file.mjs. Edit src/worker.js and public/index.html instead.\n' +
  worker.replace(marker, () => 'const EMBEDDED_HTML = `' + literal + '`;');

mkdirSync('dist', { recursive: true });
writeFileSync('dist/worker-single-file.js', out);
console.log('Wrote dist/worker-single-file.js (' + Math.round(out.length / 1024) + ' KB)');
